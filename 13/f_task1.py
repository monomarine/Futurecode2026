"""
Факториалом натурального числа  называется произведение всех чисел от 1 до  включительно, т.е. .

Напишите и проверьте рекурсивную функцию для вычисления факториала заданного числа .

На вход программе подаётся натуральное число  ().

На выходе программа должна вывести в консоль одно целое число - вычисленное значение .
"""
import sys
sys.setrecursionlimit(5000)
n = int(input())

def factorial(n):
    if n == 1:
        return 1
    return n * factorial(n - 1)

print(factorial(n))
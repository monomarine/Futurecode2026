"""
Числа Фибоначчи – бесконечная последовательность натуральных чисел ,
где первые два числа равны единице,
а каждое последующее число равно сумме двух предыдущих

Напишите и проверьте рекурсивную функцию для вычисления числа Фибоначчи с заданным номером .

На вход программе подаётся натуральное число n ().

На выходе программа должна вывести в консоль одно целое число - число Фибоначчи с номером n .
"""
from functools import cache

n = int(input())

@cache
def fib(n):
    if n <= 2:
        return 1
    else:
        return fib(n - 1) + fib(n - 2)

print(fib(n))
'''
Проверить, является ли число чётным.
Найти большее из двух чисел.
Проверить, является ли число положительным, отрицательным или нулём.
'''

n = int(input('введите число для проверки на четность'))

if n % 2 == 0:
    print('Чётное')
else:
    print('Нечётное')

# ---

if n > 0:
    print('Положительное')
elif n < 0:
    print('Отрицательное')
else:
    print('Ноль')
"""Даны два списка: A = [1, 2, 3, 4, 5] и B = [4, 5, 6, 7]. Найдите:

Элементы, которые есть в обоих списках.

Все уникальные элементы из обоих списков.
Структура: set."""

A = [1, 2, 3, 4, 5]
B = [4, 5, 6, 7]

A = set(A)
B = set(B)

print(A | B)
print(A & B)

if B in A:
    print(B)
else:
    print(A)
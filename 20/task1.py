"""
Напишите программу, создающую словарь, ключами которого
являются символы введенной строки, а значениями - количество их повторений в ней.

На вход программе подаётся строка текста, состоящая из строчных латинских букв.

На выходе программа должна вывести в консоль получившийся словарь в стандартном формате
{ключ1: значение1, ключ2: значение2, …}
. Порядок следования ключей должен соответствовать порядку появления
соответствующих символов при просмотре строки слева направо.
"""
t = "python c++ java python."
text = input()
text = text.replace(".", "")
text = text.replace("?", "")
text = text.replace(",", "")
text = text.replace("!", "")

words_count = {}
for word in text:
    if word in words_count: #если слово уже есть в словаре
        words_count[word] += 1 #увеличиваем на 1
    else: #если слово встретилось 1 раз
        words_count[word] = 1

print(words_count)
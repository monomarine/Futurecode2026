"""
Напишите программу, которая запрашивает имя и фамилию пользователя,
а затем печатает строку
«Привет, [ИМЯ] [фамилия]! Приятно познакомиться!»
(на месте [ИМЯ] [фамилия] должны появиться введённые с клавиатуры имя и фамилия пользователя, причём,
независимо от ввода, все буквы имени должны быть заглавными,
все буквы фамилии – строчными).
.
"""
name = input()
surname = input()

name = name.upper()
surname = surname.lower()

print(f"Привет, {name} {surname}! Приятно познакомиться!")

"""
Напишите программу, которая проверяет строки
на соответствие определенным правилам.

Для каждого правила создайте анонимную функцию (lambda),
которая принимает строку и возвращает True или False.

Правила:
- is_long: строка длиннее 5 символов.
- has_digit: в строке есть хотя бы одна цифра.
- starts_with_A: строка начинается с заглавной латинской буквы "A".

Затем программа должна считать одну строку с клавиатуры и
вывести три результата работы этих функций через пробел в одной строке.
"""
length_check = lambda l: len(l) > 5
has_digit = lambda l: any(l.isdigit() for l in l)
starts_with_A = lambda l: l.startswith('A')

text = input()
print(length_check(text), has_digit(text), starts_with_A(text))

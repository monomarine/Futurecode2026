'''
3 Перевести время в секундах в часы, минуты и секунды.
4 Проверить, является ли число чётным и кратным 3.
'''

# 3600 - количество секунд  вчасе
time = int(input("введите время в секундах"))
hours = time // 3600
minuts = (time % 3600) // 60
seconds = time % 60

print(f'часов - {hours} \nминут - {minuts} \nсекунд - {seconds}')
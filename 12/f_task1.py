"""
Напишите и проверьте рекурсивную функцию для вычисления суммы чисел от 1 до N.

На вход программе поступает натуральное число N.

На выходе программа должна вывести в консоль одно целое число - сумму натуральных чисел от 1 до  включительно.
"""
n = int(input())

def rec_sum(n):
    if n == 1:
        return 1
    return  n + rec_sum(n - 1)

print(rec_sum(n))
"""
Числа Фибоначчи – бесконечная последовательность натуральных чисел 1, 1, 2, 3, 5, 8, …, где первые два числа равны единице, а каждое последующее число равно сумме двух предыдущих (1+1=2, 1+2=3, 2+3=5 и т.д.).

Напишите и проверьте итерационную и рекурсивную функции для вычисления числа Фибоначчи с заданным номером .

На вход программе подаётся натуральное число .

На выходе программа должна вывести в консоль два целых числа через пробел - значения числа Фибоначчи с номером , вычисленные с помощью итерационной и рекурсивной функции соответственно.
"""
def fib(n):
    if n <= 1:
        return n
    else:
        return fib(n-1) + fib(n-2)

num = int(input())
print(fib(num))
'''
Запрашивает у пользователя число N (гарантируется, что N > 0)
Для каждого числа от 1 до N выводит:
- "Fizz", если число делится на 3
- "Buzz", если число делится на 5
- "FizzBuzz", если число делится и на 3, и на 5
- само число во всех остальных случаях.
'''

n = int(input())

for i in range(1, n + 1):
    if i % 3 == 0 and i % 5 == 0:
        print("FizzBuzz")
    elif i % 3 == 0:
        print("Fizz")
    elif i % 5 == 0:
        print("Buzz")
    else:
        print(i)
"""
Число Армстронга — число,
равное сумме своих цифр,
возведённых в степень, равную количеству цифр.

Например, 153 = 1³ + 5³ + 3³.

Найти все такие числа до N.
"""

n = int(input())

for i in range(10, n+1):
    exp = len(str(i))
    summ = 0
    for ch in str(i):
        summ += int(ch) ** exp
    if summ == i:
        print(i)
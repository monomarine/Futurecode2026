"""
В общественном транспорте билет считается «счастливым»,
если сумма первых трёх цифр шестизначного номера равна сумме последних трёх.

Определить, счастливый ли билет.

"""

ticker_number = input("введите шестизначный номер билета")

num1 = 0
for i in ticker_number[0:3]:
    num1 += int(i)

num2 = 0
for i in ticker_number[3:]:
    num2 += int(i)

if num1 == num2:
    print('счастливый билет')
else:
    print('не счастливый билет')
'''
Разработайте программу для проверки пароля, которая:
- Даёт пользователю 3 попытки на ввод правильного пароля qwerty123.
- При каждом неверном вводе показывает: "Неверный пароль! Осталось попыток: X".
- При правильном вводе выводит: "Доступ разрешён".
- После 3 ошибок блокирует доступ: "Система заблокирована!".
'''

for i in range(1,4):
    password = input()
    if password == 'qwerty123':
        print("Доступ разрешён")
        break
    else:
        print(f"Неверный пароль! Осталось попыток: {3 - i}")

else:
    print("Система заблокирована!")